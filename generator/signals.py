"""
AI-usage signals for aem-free-waf: the full config/robots.txt and the matching
Content-Usage response header rule.

Formats:
  * Content-Usage (IETF AIPREF drafts: draft-ietf-aipref-attach, draft-ietf-aipref-vocab)
  * Content-Signal (Cloudflare Content Signals Policy)
  * __usage_ai-training policy token (draft-kelley-aipref-training-preference-signal)

A crawler obeys only its most specific robots.txt group, so preferences and crawl hygiene
live in the `*` group, and named groups exist only to shut a crawler out completely.
"""
from __future__ import annotations

import re

_CONTENT_USAGE = re.compile(r"[a-z][a-z0-9-]*=[yn](?:, ?[a-z][a-z0-9-]*=[yn])*")

_RESERVATION = """\
# Rights reservation: text and data mining of this site's content for AI training is
# expressly reserved under Art. 4(3) of Directive (EU) 2019/790 (EU DSM Directive).
"""


_AI_GROUP_COMMENT = "# AI crawlers the CDN policy blocks (source: ai.robots.txt)"


def _content_usage(cfg: dict) -> str | None:
    """Returns the configured preference; rejects anything that isn't a valid statement,
    because the value ends up verbatim in a response header."""
    if "contentUsage" not in cfg:
        return None
    value = cfg["contentUsage"]
    if not isinstance(value, str) or not _CONTENT_USAGE.fullmatch(value):
        raise ValueError(f"robots.contentUsage is not a valid statement, e.g. train-ai=n: {value!r}")
    return value


def response_rules(cfg: dict) -> list[dict]:
    """responseTransformations rules that repeat the robots.txt preference as a header."""
    value = _content_usage(cfg)
    if value is None:
        return []
    return [{
        "name": "set-content-usage-header",
        "when": {"reqProperty": "tier", "equals": "publish"},
        "actions": [{"type": "set", "respHeader": "Content-Usage", "value": value}],
    }]


def _wildcard_group(cfg: dict, usage: str | None) -> list[str]:
    lines = ["# Everyone else: normal crawling, with stated AI preferences and AEM crawl hygiene",
             "User-agent: *", "Allow: /"]
    lines += [f"Allow: {path}" for path in cfg.get("allowPaths") or []]
    lines += [f"Disallow: {path}" for path in cfg.get("disallowPaths") or []]
    for param in cfg.get("disallowQueryParams") or []:
        lines += [f"Disallow: /*?{param}=", f"Disallow: /*&{param}="]
    if cfg.get("contentSignal"):
        lines.append(f"Content-Signal: {cfg['contentSignal']}")
    if usage:
        lines.append(f"Content-Usage: {usage}")
    return lines


def _closed_group(comment: str, tokens: list[str]) -> list[str]:
    if not tokens:
        return []
    # robots.txt tokens match case-insensitively; sorting first keeps the output deterministic
    unique = {t.lower(): t for t in sorted(tokens)}
    return ["", comment, *[f"User-agent: {unique[k]}" for k in sorted(unique)], "Disallow: /"]


def _sitemap_lines(cfg: dict) -> list[str]:
    sitemaps = cfg.get("sitemaps") or []
    for url in sitemaps:
        if not re.match(r"https?://", str(url)):
            raise ValueError(f"robots.sitemaps entries must be absolute URLs: {url!r}")
    if not sitemaps:
        return ["", "# Sitemap: set robots.sitemaps in waf-config.yaml (absolute URL)"]
    return ["", *[f"Sitemap: {url}" for url in sitemaps]]


def render_robots(cfg: dict, ai_tokens: list[str]) -> str:
    """Renders robots.txt. `ai_tokens` = crawlers the CDN policy blocks or rate limits."""
    usage = _content_usage(cfg)
    lines = ["# Generated by aem-free-waf. Edit waf-config.yaml, not this file.",
             *_RESERVATION.splitlines(), "", *_wildcard_group(cfg, usage)]
    lines += _closed_group("# Training opt-out tokens: these never crawl, and search visibility is unaffected",
                           [*(cfg.get("trainingOptOutTokens") or []), *(cfg.get("usageTokens") or [])])
    lines += _closed_group(_AI_GROUP_COMMENT, ai_tokens)
    lines += _sitemap_lines(cfg)
    return "\n".join(lines) + "\n"


def previous_ai_tokens(text: str) -> list[str]:
    """Reads the AI crawler group back from an earlier robots.txt (used during a feed outage)."""
    lines = text.splitlines()
    if _AI_GROUP_COMMENT not in lines:
        return []
    tokens = []
    for line in lines[lines.index(_AI_GROUP_COMMENT) + 1:]:
        if not line.startswith("User-agent: "):
            break
        tokens.append(line.removeprefix("User-agent: "))
    return tokens
